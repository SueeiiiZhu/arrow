// --- level entries ----------------------------------------------------------
//
// The catalog (`ALL_KEYS` + `KEY_TO_LOC` + `MAIN_LEVELS`) is generated by
// scripts/build-levels.mjs and committed only to-memory at build time. The
// picker shows every entry parsed from the filename; the actual level data
// (compact form) for keys outside MAIN_LEVELS is fetched on demand from
// /packs/packN.json and decoded back into a RawLevelFile.

interface Entry {
  key: string;
  name: string;
  size?: string;
  count?: number;
  tags: string[];
}

function parseEntry(key: string): Entry {
  const name = key.replace(/^\d+__/, "").replace(/\.json$/, "");
  let size: string | undefined;
  let count: number | undefined;
  let tags: string[] = [];
  for (const m of name.matchAll(/\[([^\]]+)\]/g)) {
    const g = m[1]!;
    if (/^\d+x\d+$/.test(g)) size = g;
    else if (/^\d+$/.test(g)) count = Number(g);
    else if (/[A-Za-z]/.test(g)) tags = g.split(",").map((s) => s.trim());
  }
  return { key, name, size, count, tags };
}

