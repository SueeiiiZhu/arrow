interface PackEntry {
  key: string;
  data: CompactLevel;
}

const packCache = new Map<number, PackEntry[]>();
const packInflight = new Map<number, Promise<PackEntry[]>>();

async function loadPack(packIdx: number): Promise<PackEntry[]> {
  const cached = packCache.get(packIdx);
  if (cached) return cached;
  const existing = packInflight.get(packIdx);
  if (existing) return existing;
  const p = fetch(`${import.meta.env.BASE_URL}packs/pack${packIdx}.json`)
    .then((r) => {
      if (!r.ok) throw new Error(`pack${packIdx} HTTP ${r.status}`);
      return r.json() as Promise<PackEntry[]>;
    })
    .then((data) => {
      packCache.set(packIdx, data);
      return data;
    });
  packInflight.set(packIdx, p);
  p.finally(() => packInflight.delete(packIdx));
  return p;
}

async function resolveLevel(key: string): Promise<CompactLevel | null> {
  const main = mainByKey.get(key);
  if (main) return main;
  const loc = KEY_TO_LOC[key];
  if (!loc) return null;
  const [packIdx, localIdx] = loc;
  if (packIdx < 0) return null;
  const pack = await loadPack(packIdx);
  return pack[localIdx]?.data ?? null;
}

