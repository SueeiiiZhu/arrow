// Undo / hint state ---------------------------------------------------------
const UNDO_CAP = 20;
const undoStack: GameSnapshot[] = [];
let hintArrowId: number | null = null;
let hintStart = 0;
const HINT_DURATION = 2500; // ms before highlight auto-fades

function clearUndoStack(): void {
  undoStack.length = 0;
  refreshHistoryControls();
}

function clearHint(): void {
  if (hintArrowId == null) return;
  hintArrowId = null;
  render();
}

function refreshHistoryControls(): void {
  undoBtn.disabled = undoStack.length === 0;
  hintBtn.disabled = !game || game.status !== "playing" || loadingKey != null;
}

function isHintActive(): boolean {
  return hintArrowId != null && performance.now() - hintStart < HINT_DURATION;
}

function dpr(): number {
  return Math.min(window.devicePixelRatio || 1, 2);
}

function viewSize(): { w: number; h: number } {
  const d = dpr();
  return { w: canvas.width / d, h: canvas.height / d };
}

function resize(): void {
  const d = dpr();
  const rect = canvas.getBoundingClientRect();
  canvas.width = Math.floor(rect.width * d);
  canvas.height = Math.floor(rect.height * d);
  ctx.setTransform(d, 0, 0, d, 0, 0);
  render();
}

function render(): void {
  if (!game) return;
  const { w, h } = viewSize();
  const t = fitView(game.level, w, h);

  const now = performance.now();
  const progressOverride = new Map<number, number>();
  const drawEscapedIds = new Set<number>();
  for (const [id, tw] of tweens) {
    progressOverride.set(id, evalTween(tw, now));
    if (now >= tw.start + tw.dur) {
      tweens.delete(id);
    } else if (tw.escapedAtEnd) {
      drawEscapedIds.add(id);
    }
  }
  const shakeOffsets = new Map<number, { dx: number; dy: number }>();
  for (const [id, sh] of shakes) {
    const off = evalShake(sh, now, t.cell);
    if (!off) {
      shakes.delete(id);
      continue;
    }
    shakeOffsets.set(id, off);
  }

  let highlightArrowId: number | null = null;
  let highlightPulse = 1;
  if (isHintActive()) {
    highlightArrowId = hintArrowId;
    const u = (performance.now() - hintStart) / HINT_DURATION;
    // 0.55 + 0.45*sin gives a perceptible but non-flickery pulse; fade tail.
    const pulseAmp = 0.55 + 0.45 * Math.sin(performance.now() * 0.012);
    const fade = u < 0.8 ? 1 : Math.max(0, 1 - (u - 0.8) / 0.2);
    highlightPulse = pulseAmp * fade;
  }

  drawGame(ctx as any, game, t, {
    showPaths: showPathsBox.checked,
    progressOverride,
    shakeOffsets,
    drawEscapedIds,
    highlightArrowId,
    highlightPulse,
  });

  if (game.status === "won" && winStart != null) {
    const phase = (performance.now() - winStart) / 1000;
    winHitbox = drawWinOverlay(ctx as any, w, h, phase);
  } else {
    winHitbox = null;
  }
}

function updateStatus(): void {
  if (loadingKey != null) {
    status.textContent = "加载中…";
    status.style.color = "#94a3b8";
    return;
  }
  if (!game) {
    status.textContent = "";
    return;
  }
  const remaining = game.arrows.filter((a) => !a.escaped).length;
  if (game.status === "won") {
    status.textContent = "通关！";
    status.style.color = "#22c55e";
  } else {
    status.textContent = `剩余 ${remaining}/${game.arrows.length}`;
    status.style.color = "#e2e8f0";
  }
}

function updatePickerLabel(): void {
  const entry = entries.find((e) => e.key === currentKey);
  const idx = entry ? entries.indexOf(entry) + 1 : 0;
  pickerLabel.textContent = entry ? `${idx}/${entries.length}  ${entry.name}` : "—";
}

function selectLevel(key: string): void {
  const entry = entries.find((e) => e.key === key);
  if (!entry) return;
  currentKey = key;
  loadingKey = key;
  game = null;
  clearAnimations();
  clearUndoStack();
  hintArrowId = null;
  winStart = null;
  meta.textContent = "加载中…";
  updatePickerLabel();
  updateStatus();
  refreshHistoryControls();
  render();
  resolveLevel(key)
    .then((compact) => {
      if (loadingKey !== key) return; // user moved on already
      if (!compact) {
        meta.textContent = `[关卡缺失] ${key}`;
        loadingKey = null;
        return;
      }
      const level = loadLevel(decodeCompact(compact));
      const err = validateLevel(level);
      meta.textContent = err
        ? `[校验失败] ${err}`
        : `${level.width}×${level.height}  ${level.arrows.length} 箭头`;
      game = createGame(level);
      loadingKey = null;
      progress.lastKey = key;
      persist();
      updateStatus();
      refreshHistoryControls();
      render();
    })
    .catch((e) => {
      if (loadingKey !== key) return;
      meta.textContent = `[加载失败] ${String((e as Error).message ?? e)}`;
      loadingKey = null;
      render();
    });
}

function gotoNextLevel(): void {
  const i = entries.findIndex((e) => e.key === currentKey);
  if (i >= 0 && i < entries.length - 1) selectLevel(entries[i + 1]!.key);
}

function handlePointer(clientX: number, clientY: number): void {
  if (!game) return;
  const rect = canvas.getBoundingClientRect();
  const px = clientX - rect.left;
  const py = clientY - rect.top;

  // Win-overlay button takes priority while the level is won.
  if (game.status === "won" && winHitbox) {
    const hit = hitTestOverlay(winHitbox, px, py);
    if (hit === "next") {
      synth.click();
      gotoNextLevel();
    }
    return;
  }

  if (isAnimating()) return;
  const { w, h } = viewSize();
  const t = fitView(game.level, w, h);
  const cell = pickCell(px, py, t);
  if (cell.x < 0 || cell.y < 0 || cell.x >= game.level.width || cell.y >= game.level.height) {
    return;
  }
  const arrow = findArrowAt(game, cell);
  if (!arrow) return;
  const before = arrow.progress;
  const snap = snapshotGame(game);
  const result = tryPull(game, arrow.id);
  const after = arrow.progress;
  if (result.steps > 0) {
    pushUndo(snap);
    if (hintArrowId === arrow.id) clearHint();
    startTween(arrow.id, before, after, result.escaped);
    if (result.escaped) synth.escape();
    else synth.whoosh(result.steps);
  } else {
    startShake(arrow.id, arrow.data.facing);
    synth.thud();
  }
  if (result.won && currentKey) {
    progress.completed.add(currentKey);
    persist();
    winStart = performance.now();
    synth.win();
    ensureRAF();
  }
  updateStatus();
  refreshHistoryControls();
  render();
}

function pushUndo(snap: GameSnapshot): void {
  undoStack.push(snap);
  if (undoStack.length > UNDO_CAP) undoStack.shift();
  refreshHistoryControls();
}

function doUndo(): void {
  if (!game) return;
  if (loadingKey != null) return;
  if (isAnimating()) return;
  const snap = undoStack.pop();
  if (!snap) return;
  restoreGame(game, snap);
  clearAnimations();
  winStart = null;
  hintArrowId = null;
  synth.click();
  updateStatus();
  refreshHistoryControls();
  render();
}

function doHint(): void {
  if (!game || game.status !== "playing") return;
  if (loadingKey != null || isAnimating()) return;
  hintBtn.disabled = true;
  hintBtn.textContent = "💡 思考…";
  // findNextMove is synchronous; defer one frame so the disabled-state paints
  // before we possibly block for a few hundred ms on a hard level.
  requestAnimationFrame(() => {
    const moveId = game ? findNextMove(game, Date.now() + 2000) : null;
    hintBtn.textContent = "💡 提示";
    if (moveId == null) {
      hintBtn.textContent = "💡 无解";
      setTimeout(() => {
        hintBtn.textContent = "💡 提示";
        refreshHistoryControls();
      }, 1200);
      return;
    }
    hintArrowId = moveId;
    hintStart = performance.now();
    synth.click();
    refreshHistoryControls();
    ensureRAF();
  });
}

